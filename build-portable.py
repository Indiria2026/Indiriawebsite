"""Rebuild the two classic-script bundles for this static INDIRIA export.

Run with Python 3 after editing the included source .js/.mjs files.
No third-party dependencies. This intentionally handles only this site's
known module graph and rejects unsupported imports instead of guessing.
"""
from pathlib import Path, PurePosixPath
import json
import posixpath
import re

ROOT = Path(__file__).resolve().parent

def bundle(files, output):
    built = set()
    chunks = ['/* INDIRIA portable export: generated by build-portable.py. */',
              '(() => {\n"use strict";\nconst modules = Object.create(null);']
    for filename in files:
        code = (ROOT / filename).read_text(encoding='utf-8')
        if filename == 'assets/moments/moments.js':
            # The Site has exactly one visual moment. Resolve it locally rather
            # than using dynamic import(), which is blocked on file:// pages.
            old_base = "new URL('./', import.meta.url)"
            old_import = 'import(new URL(`${id}/moment.js`, BASE).href)'
            assert old_base in code and old_import in code
            code = code.replace(old_base, "new URL('assets/moments/', document.baseURI)")
            code = code.replace(old_import, "Promise.resolve(modules['assets/moments/' + id + '/moment.js'])")

        def imports(match):
            statement = match.group(0)
            parsed = re.fullmatch(r"import\s+(?:(.*?)\s+from\s+)?['\"]([^'\"]+)['\"];?", statement)
            if not parsed:
                raise ValueError('Unsupported import in ' + filename + ': ' + statement)
            binding, specifier = parsed.groups()
            target = posixpath.normpath(str(PurePosixPath(filename).parent / specifier))
            if target not in built:
                raise ValueError('Missing or unordered dependency: ' + target)
            if not binding:
                return ''
            if binding.startswith('{'):
                binding = re.sub(r'\bas\b', ':', binding)
            elif binding.startswith('* as '):
                binding = binding[5:]
            else:
                raise ValueError('Unsupported import binding: ' + binding)
            return 'const ' + binding + ' = modules[' + json.dumps(target) + '];'

        code = re.sub(r'^import[^\n]+', imports, code, flags=re.M)
        exports = re.findall(r'^export\s+(?:const|let|function)\s+(\w+)', code, re.M)
        has_default = bool(re.search(r'^export default ', code, re.M))
        code = re.sub(r'^export default ', 'const __default = ', code, flags=re.M)
        code = re.sub(r'^export (?=(?:const|let|function)\b)', '', code, flags=re.M)
        executable = re.sub(r'/\*.*?\*/', '', code, flags=re.S)
        if re.search(r'^\s*(?:import|export)\s', executable, re.M):
            raise ValueError('Unconverted module syntax in ' + filename)
        values = exports + (['default: __default'] if has_default else [])
        chunks.append('\n// Source: ' + filename + '\nmodules[' + json.dumps(filename) +
                      '] = (() => {\n' + code + '\nreturn {' + ', '.join(values) + '};\n})();')
        built.add(filename)
    chunks.append('\n})();\n')
    (ROOT / output).write_text('\n'.join(chunks), encoding='utf-8')

bundle(['translations-en.js', 'translations-zh.js', 'zoom-math.mjs', 'i18n.js',
        'app.js', 'observation-gallery.js', 'interactive.js'], 'site.js')
bundle(['assets/motion/motion.js', 'assets/moments/lib.js',
        'assets/moments/picture-develops/moment.js', 'assets/moments/moments.js'], 'effects.js')
print('Built site.js and effects.js; no ES module loading is needed by index.html.')
